-- =============================================================================
-- CounselGrid: Enterprise Outside Counsel & Conflict Governance System
-- PostgreSQL / Supabase migration
--
-- Apply order:  schema.sql  ->  seed.sql  ->  post_seed.sql
-- (python -m counselgrid.bootstrap runs all three against SUPABASE_DB_URL)
-- =============================================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- -----------------------------------------------------------------------------
-- Reference domains (kept as CHECK constraints so the schema stays portable
-- to the SQLite fallback, which has no ENUM type).
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS outside_firms (
    firm_id                                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firm_name                               TEXT        NOT NULL UNIQUE,
    hq_city                                 TEXT        NOT NULL,
    state                                   CHAR(2)     NOT NULL,
    am_law_tier                             TEXT        NOT NULL
        CHECK (am_law_tier IN ('AmLaw 50', 'AmLaw 100', 'Regional Boutique')),
    diversity_certified                     BOOLEAN     NOT NULL DEFAULT FALSE,
    msa_status                              TEXT        NOT NULL
        CHECK (msa_status IN ('Active', 'Under Review', 'Expired')),
    msa_expiration_date                     DATE        NOT NULL,
    blended_hourly_rate_usd                 NUMERIC(8,2) NOT NULL CHECK (blended_hourly_rate_usd > 0),
    alternative_fee_arrangement_available   BOOLEAN     NOT NULL DEFAULT FALSE,
    cyber_compliance_score                  SMALLINT    NOT NULL
        CHECK (cyber_compliance_score BETWEEN 1 AND 100)
);

CREATE TABLE IF NOT EXISTS firm_practice_capabilities (
    capability_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firm_id                 INTEGER  NOT NULL REFERENCES outside_firms (firm_id) ON DELETE CASCADE,
    corporate_domain        TEXT     NOT NULL CHECK (corporate_domain IN (
                                'M&A / Corporate Governance',
                                'International Trade & Customs',
                                'Supply Chain & Commercial Contracts',
                                'IP & Patent Litigation',
                                'Regulatory & Antitrust',
                                'Labor & Employment',
                                'Data Privacy & Cybersecurity')),
    partner_bench_depth     SMALLINT NOT NULL CHECK (partner_bench_depth >= 0),
    jurisdiction_coverage   TEXT     NOT NULL,
    UNIQUE (firm_id, corporate_domain)
);

CREATE TABLE IF NOT EXISTS conflict_registry (
    conflict_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firm_id                 INTEGER  NOT NULL REFERENCES outside_firms (firm_id) ON DELETE RESTRICT,
    adverse_entity_name     TEXT     NOT NULL CHECK (length(trim(adverse_entity_name)) > 0),
    matter_type             TEXT     NOT NULL,
    conflict_severity       TEXT     NOT NULL CHECK (conflict_severity IN (
                                'Hard Block - Active Representation',
                                'Soft Check - Historical/Waivable',
                                'Clear')),
    logged_date             DATE     NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE IF NOT EXISTS matter_engagements (
    matter_id                           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    internal_department                 TEXT     NOT NULL CHECK (internal_department IN (
                                            'Supply Chain', 'Corporate Affairs', 'M&A', 'HR', 'Engineering')),
    matter_title                        TEXT     NOT NULL,
    corporate_domain                    TEXT     NOT NULL CHECK (corporate_domain IN (
                                            'M&A / Corporate Governance',
                                            'International Trade & Customs',
                                            'Supply Chain & Commercial Contracts',
                                            'IP & Patent Litigation',
                                            'Regulatory & Antitrust',
                                            'Labor & Employment',
                                            'Data Privacy & Cybersecurity')),
    opposing_or_counterparty_entity     TEXT     NOT NULL,
    estimated_budget_usd                NUMERIC(14,2) NOT NULL CHECK (estimated_budget_usd > 0),
    selected_firm_id                    INTEGER  REFERENCES outside_firms (firm_id) ON DELETE RESTRICT,
    fee_structure                       TEXT     NOT NULL CHECK (fee_structure IN (
                                            'Hourly', 'Capped Fee', 'Fixed Retainer')),
    status                              TEXT     NOT NULL DEFAULT 'Intake' CHECK (status IN (
                                            'Intake', 'Active', 'On Hold', 'Closed')),
    estimated_hours                     INTEGER  NOT NULL DEFAULT 0 CHECK (estimated_hours >= 0),
    actual_spend_usd                    NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (actual_spend_usd >= 0),
    created_at                          TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Append-only audit trail of every conflict-gate decision behind an assignment.
CREATE TABLE IF NOT EXISTS conflict_screening_log (
    screening_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matter_id           INTEGER  NOT NULL REFERENCES matter_engagements (matter_id) ON DELETE CASCADE,
    firm_id             INTEGER  NOT NULL REFERENCES outside_firms (firm_id) ON DELETE RESTRICT,
    gate_outcome        TEXT     NOT NULL CHECK (gate_outcome IN (
                            'Hard Block', 'Soft Check - Waiver Required', 'Eligible',
                            'Ineligible - MSA', 'Ineligible - No Domain Capability')),
    matched_entity      TEXT,
    match_score         NUMERIC(5,1),
    governance_score    NUMERIC(5,1),
    screened_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_capabilities_domain      ON firm_practice_capabilities (corporate_domain);
CREATE INDEX IF NOT EXISTS idx_conflicts_firm           ON conflict_registry (firm_id);
CREATE INDEX IF NOT EXISTS idx_conflicts_entity_trgm    ON conflict_registry USING gin (lower(adverse_entity_name) gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_matters_firm             ON matter_engagements (selected_firm_id);
CREATE INDEX IF NOT EXISTS idx_matters_department       ON matter_engagements (internal_department);
CREATE INDEX IF NOT EXISTS idx_screening_matter         ON conflict_screening_log (matter_id);

-- -----------------------------------------------------------------------------
-- Row-Level Security
--
-- Roles:
--   anon               no access to any table.
--   authenticated      read access for every signed-in legal user; writes only
--                      when the Supabase JWT carries app_metadata.role of
--                      'legal_ops' or 'gc_admin'.
--   counselgrid_app    service role used by the Streamlit server. Reads all,
--                      inserts conflicts / matters / screening logs, updates
--                      matters. It can never UPDATE or DELETE a conflict entry,
--                      which keeps the registry append-only.
-- -----------------------------------------------------------------------------

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'counselgrid_app') THEN
        CREATE ROLE counselgrid_app NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        CREATE ROLE authenticated NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        CREATE ROLE anon NOLOGIN;
    END IF;
END
$$;

-- Lets the migrating user (Supabase: postgres) run SET ROLE counselgrid_app,
-- which is how the application server drops into the RLS-governed role.
GRANT counselgrid_app TO CURRENT_USER;

-- Supabase exposes auth.jwt(); a stub is created only when it is absent
-- (plain PostgreSQL), so the same migration runs everywhere.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
        WHERE n.nspname = 'auth' AND p.proname = 'jwt'
    ) THEN
        CREATE SCHEMA IF NOT EXISTS auth;
        EXECUTE $fn$
            CREATE FUNCTION auth.jwt() RETURNS jsonb LANGUAGE sql STABLE AS
            'SELECT coalesce(nullif(current_setting(''request.jwt.claims'', true), ''''), ''{}'')::jsonb'
        $fn$;
    END IF;
END
$$;

CREATE OR REPLACE FUNCTION public.counselgrid_is_legal_ops() RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') IN ('legal_ops', 'gc_admin')
$$;

GRANT USAGE ON SCHEMA public TO counselgrid_app, authenticated;
GRANT USAGE ON SCHEMA auth TO counselgrid_app, authenticated;
REVOKE ALL ON outside_firms, firm_practice_capabilities, conflict_registry,
              matter_engagements, conflict_screening_log FROM anon;

GRANT SELECT ON outside_firms, firm_practice_capabilities, conflict_registry,
                matter_engagements, conflict_screening_log TO authenticated, counselgrid_app;
GRANT INSERT ON conflict_registry, matter_engagements, conflict_screening_log TO authenticated, counselgrid_app;
GRANT UPDATE ON matter_engagements, outside_firms TO authenticated, counselgrid_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO authenticated, counselgrid_app;

ALTER TABLE outside_firms               ENABLE ROW LEVEL SECURITY;
ALTER TABLE firm_practice_capabilities  ENABLE ROW LEVEL SECURITY;
ALTER TABLE conflict_registry           ENABLE ROW LEVEL SECURITY;
ALTER TABLE matter_engagements          ENABLE ROW LEVEL SECURITY;
ALTER TABLE conflict_screening_log      ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS firms_read          ON outside_firms;
DROP POLICY IF EXISTS firms_update_ops    ON outside_firms;
DROP POLICY IF EXISTS caps_read           ON firm_practice_capabilities;
DROP POLICY IF EXISTS conflicts_read      ON conflict_registry;
DROP POLICY IF EXISTS conflicts_insert    ON conflict_registry;
DROP POLICY IF EXISTS matters_read        ON matter_engagements;
DROP POLICY IF EXISTS matters_insert      ON matter_engagements;
DROP POLICY IF EXISTS matters_update      ON matter_engagements;
DROP POLICY IF EXISTS screening_read      ON conflict_screening_log;
DROP POLICY IF EXISTS screening_insert    ON conflict_screening_log;

CREATE POLICY firms_read ON outside_firms
    FOR SELECT TO authenticated, counselgrid_app USING (true);
CREATE POLICY firms_update_ops ON outside_firms
    FOR UPDATE TO authenticated, counselgrid_app
    USING (current_user = 'counselgrid_app' OR public.counselgrid_is_legal_ops())
    WITH CHECK (current_user = 'counselgrid_app' OR public.counselgrid_is_legal_ops());

CREATE POLICY caps_read ON firm_practice_capabilities
    FOR SELECT TO authenticated, counselgrid_app USING (true);

CREATE POLICY conflicts_read ON conflict_registry
    FOR SELECT TO authenticated, counselgrid_app USING (true);
CREATE POLICY conflicts_insert ON conflict_registry
    FOR INSERT TO authenticated, counselgrid_app
    WITH CHECK (current_user = 'counselgrid_app' OR public.counselgrid_is_legal_ops());

CREATE POLICY matters_read ON matter_engagements
    FOR SELECT TO authenticated, counselgrid_app USING (true);
CREATE POLICY matters_insert ON matter_engagements
    FOR INSERT TO authenticated, counselgrid_app
    WITH CHECK (current_user = 'counselgrid_app' OR public.counselgrid_is_legal_ops());
CREATE POLICY matters_update ON matter_engagements
    FOR UPDATE TO authenticated, counselgrid_app
    USING (current_user = 'counselgrid_app' OR public.counselgrid_is_legal_ops())
    WITH CHECK (current_user = 'counselgrid_app' OR public.counselgrid_is_legal_ops());

CREATE POLICY screening_read ON conflict_screening_log
    FOR SELECT TO authenticated, counselgrid_app USING (true);
CREATE POLICY screening_insert ON conflict_screening_log
    FOR INSERT TO authenticated, counselgrid_app
    WITH CHECK (current_user = 'counselgrid_app' OR public.counselgrid_is_legal_ops());

COMMIT;
